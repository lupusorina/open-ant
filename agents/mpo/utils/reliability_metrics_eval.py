"""Compute rl-reliability-metrics' *offline* metrics on repeated rollouts of a
single frozen policy per seed, for the 2empo run set.

Metrics computed (paper naming -> repo class, from metrics_offline.py):
  DF (Dispersion across Fixed-Policy Rollouts) -> IqrAcrossRollouts
  RF (Risk across Fixed-Policy Rollouts)       -> LowerCVaRAcrossRollouts

These are different in kind from reliability_metrics_2empo.py's DT/SRT/LRT/DR/RR:
those are all computed from the *training curve* (performance over time, or
across independently-trained seeds). DF/RF instead require rolling out one
FIXED policy N times and looking at the spread/tail-risk of the resulting
episode returns -- so unlike the other metrics, this data doesn't already
exist in the training logs (reward.py only ever logs a rolling mean of
episode returns, never the individual returns) and has to be generated by
actually running the environment here.

For each seed, this script:
  1. finds that seed's run directory (preferring the continuous_mpo_* /
     phase-2 folder, i.e. the final continual-learning policy, falling back
     to mpo_* / phase-1 if no phase-2 run exists -- see RUN_PREFIX_PRIORITY),
  2. loads its checkpoint at CHECKPOINT_STEP (must be set explicitly below --
     the same step is used for every seed, so DF/RF stay comparable across
     seeds),
  3. re-creates that run's exact env (env_id, dt, model_path, task, reward
     scale, ...) from the run's own saved args.json,
  4. rolls the frozen policy out N_ROLLOUTS times with deterministic
     (mean-action) control, recording one total return per rollout.

A "rollout" here is a fixed number of steps (ROLLOUT_LENGTH_STEPS), not a
natural episode. This env has no built-in episode time limit -- an episode
only ends early via task-specific truncation or going out of bounds/NaN
(see ant_mujoco.py's _get_truncated_out_of_bounds_or_nans) -- so a
well-trained policy can simply never terminate. The paper's own definition
allows for this ("A rollout may be a fixed number of actions, or an episode
otherwise defined"), so each rollout here just runs for
ROLLOUT_LENGTH_STEPS steps, ending early only if the env itself terminates/
truncates first.

Seeds are rolled out in parallel worker processes (one seed per process);
each worker builds its own env + actor and never touches another seed's
state, so seeds cannot influence each other. Everything runs on CPU
(actor is a small MLP -- no benefit to GPU here, and it avoids CUDA-in-
subprocess headaches when many seeds run at once).
"""

import argparse
import glob
import json
import multiprocessing as mp
import os
import re
import sys

import numpy as np
import pandas as pd
import torch

RL_RELIABILITY_REPO = "/home/serenaliu/caltech_linc_home/rl-reliability-metrics"
sys.path.insert(0, RL_RELIABILITY_REPO)
from rl_reliability_metrics.metrics import metrics_offline  # noqa: E402

MPO_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, MPO_DIR)
from envs import is_gymnasium_env, make_envs  # noqa: E402
from nn import AcmeActor  # noqa: E402

sys.path.insert(0, os.path.abspath(os.path.join(MPO_DIR, "../../embodied_ant_env")))
from embodied_ant_env import ForwardTask, BackAndForthTask  # noqa: E402


# =========================== Config -- edit here ===========================

RUNS_DIR = "/data2/serenaliu_data/2empo"

# Set to an explicit list of ints to pin the seed set. Set to None to
# auto-discover every seed with a run dir matching RUN_PREFIX_PRIORITY.
SEEDS = [1]

# Which run to treat as "the" policy for a seed, in priority order. The
# 2empo seeds run mpo_* (phase 1) then continuous_mpo_* (phase 2); we want
# the *final* trained policy, so phase 2 is preferred when it exists.
RUN_PREFIX_PRIORITY = ["continuous_mpo", "mpo"]

# Number of fixed-policy rollouts (episodes) per seed -- this is "N" in the
# paper's Dispersion/Risk across Fixed-Policy Rollouts metrics.
N_ROLLOUTS = 30

# Steps per rollout (see module docstring -- this env has no built-in episode
# time limit, so we define a rollout as a fixed number of steps rather than
# waiting for a natural termination that may never come). 1000 steps at the
# default dt=0.12 is ~120s of sim time, matching the averaging window
# reward.py already uses elsewhere in this pipeline.
ROLLOUT_LENGTH_STEPS = 1000

# Which training step's checkpoint to evaluate, e.g. 96000 -- the same step
# is used for every seed. Must be set explicitly (no "latest" fallback):
# seeds don't all reach the same final step, so silently using "latest"
# would mean each seed's DF/RF describes a different point in training and
# isn't comparable across seeds.
CHECKPOINT_STEP = 200000

# CVaR tail fraction for RF (lower tail = worst-case rollouts).
RF_ALPHA = 0.05

# Passed straight to metrics_offline: None (raw units), a float divisor, or
# "median_perf" (normalize by the median rollout performance per seed).
BASELINE = None

# How many seeds to roll out at once. Each worker is single-threaded CPU
# (see rollout_fixed_policy), so this can reasonably go up to core count.
MAX_PARALLEL_SEEDS = min(32, os.cpu_count() or 1)

OUT_DIR = os.path.join(RUNS_DIR, "reliability_metrics")

# =============================================================================


def discover_seeds():
    seed_re = re.compile(r"seed_(\d+)$")
    seeds = set()
    for prefix in RUN_PREFIX_PRIORITY:
        for path in glob.glob(f"{RUNS_DIR}/{prefix}_*_seed_*"):
            m = seed_re.search(path)
            if m:
                seeds.add(int(m.group(1)))
    return sorted(seeds)


def find_run_dir(seed):
    for prefix in RUN_PREFIX_PRIORITY:
        matches = sorted(glob.glob(f"{RUNS_DIR}/{prefix}_*_seed_{seed}"), reverse=True)
        if matches:
            return matches[0]
    raise FileNotFoundError(
        f"seed {seed}: no run directory under {RUNS_DIR} matching any of "
        f"{RUN_PREFIX_PRIORITY}")


def find_checkpoint(weights_path, checkpoint_step):
    if checkpoint_step is None:
        raise ValueError(
            "CHECKPOINT_STEP is None -- set it to an explicit training step "
            "at the top of this script (this script does not fall back to "
            "'latest checkpoint').")
    ckpts = [f for f in os.listdir(weights_path) if f.endswith(".pth")]
    if not ckpts:
        raise FileNotFoundError(f"No .pth checkpoints found in {weights_path}")

    chosen = f"checkpoint_{checkpoint_step}.pth"
    if chosen not in ckpts:
        ckpts.sort(key=lambda x: int(x.split("_")[-1].split(".")[0]))
        raise FileNotFoundError(
            f"checkpoint_step={checkpoint_step} not found in {weights_path}. "
            f"Available: {ckpts}")
    return os.path.join(weights_path, chosen)


def build_task(args):
    if is_gymnasium_env(args.env_id):
        return None
    if args.task_type == "forward":
        return ForwardTask()
    if args.task_type == "back_and_forth":
        return BackAndForthTask(
            radius=args.radius_back_and_forth,
            origin=np.array(args.origin_back_and_forth),
        )
    raise ValueError(f"Unknown task_type: {args.task_type!r}")


def rollout_fixed_policy(seed):
    """Worker entry point: roll out one seed's frozen final policy N_ROLLOUTS times.

    Returns (seed, returns) where returns is a 1-D array of per-episode totals.
    """
    torch.set_num_threads(1)

    run_dir = find_run_dir(seed)
    weights_path = os.path.join(run_dir, "weights_and_args")
    with open(os.path.join(weights_path, "args.json")) as f:
        args = argparse.Namespace(**json.load(f))

    # This is a lightweight eval-only rollout, not a training run -- override
    # anything training-specific / expensive that we don't need.
    args.num_envs = 1
    args.capture_video = False
    args.render_mode = None  # physics-only rollout, no need to render frames
    args.cuda = False

    checkpoint_path = find_checkpoint(weights_path, CHECKPOINT_STEP)
    task = build_task(args)

    env_raw, _ = make_envs(
        args, task,
        disk_folder="",
        run_name=f"eval_fixed_policy_seed_{seed}",
        runs_directory="/tmp",
        wrap_skrl=False,
    )

    obs_dim = int(np.prod(env_raw.single_observation_space.shape))
    act_dim = int(np.prod(env_raw.single_action_space.shape))
    actor = AcmeActor(
        obs_dim=obs_dim,
        act_dim=act_dim,
        act_low=env_raw.single_action_space.low.astype(np.float32),
        act_high=env_raw.single_action_space.high.astype(np.float32),
        layer_sizes=tuple(args.policy_layer_sizes),
        init_scale=args.policy_init_scale,
        min_scale=args.policy_min_scale,
    )
    checkpoint = torch.load(checkpoint_path, map_location="cpu")
    actor.load_state_dict(checkpoint["actor"])
    actor.eval()

    print(f"[seed {seed}] rolling out {N_ROLLOUTS} x {ROLLOUT_LENGTH_STEPS}-step rollouts of "
          f"{os.path.basename(checkpoint_path)} from {os.path.basename(run_dir)}",
          flush=True)

    returns = []
    obs, _ = env_raw.reset(seed=seed)
    with torch.no_grad():
        for k in range(N_ROLLOUTS):
            if k > 0:
                # Fresh initial state; RNG continues advancing from the
                # seeded stream above so each rollout differs.
                obs, _ = env_raw.reset()
            ep_return = 0.0
            for _ in range(ROLLOUT_LENGTH_STEPS):
                action = actor(torch.as_tensor(obs, dtype=torch.float32)).mean.numpy()
                obs, reward, terminated, truncated, _ = env_raw.step(action)
                ep_return += float(reward[0])
                if bool(terminated[0] or truncated[0]):
                    break
            returns.append(ep_return)

    env_raw.close()
    returns = np.array(returns, dtype=np.float64)
    print(f"[seed {seed}] done: mean={returns.mean():.4g} "
          f"min={returns.min():.4g} max={returns.max():.4g}", flush=True)
    return seed, returns


def main():
    seeds = SEEDS if SEEDS is not None else discover_seeds()
    print(f"Seeds: {seeds}")
    print(f"N_ROLLOUTS per seed: {N_ROLLOUTS}  "
          f"(up to {MAX_PARALLEL_SEEDS} seeds in parallel, CHECKPOINT_STEP={CHECKPOINT_STEP})")

    results = {}
    ctx = mp.get_context("spawn")
    with ctx.Pool(processes=min(MAX_PARALLEL_SEEDS, len(seeds))) as pool:
        for seed, returns in pool.imap_unordered(rollout_fixed_policy, seeds):
            results[seed] = returns

    used_seeds = sorted(results)
    rollout_sets = [
        np.stack([np.arange(len(results[s])), results[s]])
        for s in used_seeds
    ]

    df_metric = metrics_offline.IqrAcrossRollouts(baseline=BASELINE)
    df_values = df_metric(rollout_sets)

    rf_metric = metrics_offline.LowerCVaRAcrossRollouts(alpha=RF_ALPHA, baseline=BASELINE)
    rf_values = rf_metric(rollout_sets)

    per_seed_df = pd.DataFrame({
        "seed": used_seeds,
        "n_rollouts": [len(results[s]) for s in used_seeds],
        "mean_return": [results[s].mean() for s in used_seeds],
        "median_return": [np.median(results[s]) for s in used_seeds],
        "DF_IqrAcrossRollouts": df_values,
        "RF_LowerCVaRAcrossRollouts": rf_values,
    })

    print("\n=== Per-seed fixed-policy rollout metrics ===")
    print(per_seed_df.to_string(index=False))

    print("\n=== Summary (median across seeds) ===")
    print(f"DF (median IQR across rollouts):        {np.median(df_values):.6g}")
    print(f"RF (median lower-CVaR across rollouts): {np.median(rf_values):.6g}")

    os.makedirs(OUT_DIR, exist_ok=True)
    per_seed_df.to_csv(os.path.join(OUT_DIR, "fixed_policy_rollout_metrics.csv"), index=False)

    raw_rows = [
        {"seed": s, "rollout_index": i, "return": ret}
        for s in used_seeds
        for i, ret in enumerate(results[s])
    ]
    pd.DataFrame(raw_rows).to_csv(
        os.path.join(OUT_DIR, "fixed_policy_rollouts_raw.csv"), index=False)

    print(f"\nSaved results to {OUT_DIR}/")


if __name__ == "__main__":
    main()
